/**
 * The world's land outline as one SVG path, for the map card.
 *
 *   node scripts/assets/world-map.mjs <ne_110m_land.geojson>
 *
 * Input: Natural Earth 1:110m "land" (public domain) —
 * https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_land.geojson
 * Output: src/record/world-map.ts. Equirectangular, viewBox "0 0 360 150":
 * x = longitude + 180, y = 90 − latitude; everything south of 60°S is cut.
 * Points are rounded to half a degree and repeats dropped.
 */
import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2];
if (!source) throw new Error("usage: node scripts/assets/world-map.mjs <ne_110m_land.geojson>");
const { features } = JSON.parse(readFileSync(source, "utf8"));

const round = (n) => Math.round(n * 2) / 2;
const rings = features.flatMap((f) => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates)).map((polygon) => polygon[0]);

let path = "";
for (const ring of rings) {
  if (ring.every(([, lat]) => lat < -60)) continue;
  const points = [];
  for (const [lon, lat] of ring) {
    const p = `${round(lon + 180)} ${round(90 - Math.max(lat, -60))}`;
    if (points[points.length - 1] !== p) points.push(p);
  }
  if (points.length > 3) path += `M${points.join("L")}Z`;
}

writeFileSync(
  "src/record/world-map.ts",
  `/** generated by scripts/assets/world-map.mjs from Natural Earth 1:110m land (public domain) — do not edit */\nexport const WORLD_VIEWBOX = "0 0 360 150";\nexport const WORLD_LAND =\n  "${path}";\n`,
);
console.log(`wrote src/record/world-map.ts (${(path.length / 1024).toFixed(1)} kB, ${rings.length} rings)`);
